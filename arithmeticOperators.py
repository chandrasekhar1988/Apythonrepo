#పైథాన్‌లో ముఖ్యమైన 7 Arithmetic Operators ఉన్నాయి

a = 15
b = 4

# కూడిక (Addition)
print("Addition (+):", a + b)

# తీసివేత (Subtraction)
print("Subtraction (-):", a - b)

# గుణకారం (Multiplication)
print("Multiplication (*):", a * b)

# భాగహారం (Division)
print("Division (/):", a / b)

# ఫ్లోర్ భాగహారం (Floor Division) - ఇది పాయింట్లు తీసేసి కేవలం పూర్ణాంకాన్ని ఇస్తుంది
print("Floor Division (//):", a // b)

# శేషం (Modulus) - భాగహారం చేసినప్పుడు మిగిలే శేషం
print("Modulus (%):", a % b)

# ఘాతం (Exponent) - a power b
print("Exponent (**):", a ** b)